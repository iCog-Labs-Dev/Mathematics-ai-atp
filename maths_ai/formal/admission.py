"""Admit a request's input into one validated task, for either input kind.

``goal`` inputs are parsed by the shared declaration parser and rendered to a
closed statement over their universe levels; the provider writes a Lean source
for them (``source_origin: generated-from-text``). ``source`` inputs are
resolved from the artifact store by hash, and the backend's own Lean runtime
elaborates the named declaration with its proof replaced by ``sorry``: the
goal at that ``sorry`` is the declaration's signature with its outer binders
introduced, in the file's own namespaces, notation and universes. The
declaration's proof is never elaborated and later declarations are dropped,
so the target can never be its own premise.

Both kinds produce an ``AdmittedTask``: a seed the backend searches, the
closed statement it replays, and a content-addressed input manifest that
binds everything the run and any later replay rely on. A failed source
admission is a typed rejection; it is never retried as text.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any, Awaitable, Callable

from maths_ai.lean_replay import ReplayInputError, render_replay, seed_from_text
from maths_ai.lean_replay.lexer import LexError, tokenize
from maths_ai.lean_replay.seed import StructuredLocal, seed_from_records

from .artifacts import ArtifactError, ArtifactStore
from .contract import GoalInput, SourceInput

INPUT_MANIFEST_FORMAT = "maths-ai-formal-input-v1"
GENERATED_THEOREM = "formal_target"

__all__ = [
    "AdmissionRejected",
    "AdmittedTask",
    "admit_goal",
    "admit_source",
    "generated_source",
    "seed_from_spec",
    "source_seed",
    "split_header",
    "target_unit_signature",
]


class AdmissionRejected(ValueError):
    """The input cannot be admitted faithfully; ``category`` says why."""

    def __init__(self, category: str, detail: str) -> None:
        super().__init__(detail)
        self.category = category
        self.detail = detail


@dataclass(frozen=True)
class AdmittedTask:
    kind: str
    seed_spec: dict[str, Any]
    statement: dict[str, Any]
    manifest: dict[str, Any]
    input_artifact_hash: str
    source_artifact_hash: str
    source_origin: str
    display_goal: str


def seed_from_spec(spec: dict[str, Any]):
    """Rebuild the search seed from its stored, JSON-safe specification."""
    if spec["kind"] == "text":
        return seed_from_text(
            goal=spec["goal"], hypotheses=list(spec["hypotheses"]), source=spec.get("source") or {}
        )
    if spec["kind"] == "structured":
        return seed_from_records(
            spec["target_sexp"],
            [StructuredLocal(**record) for record in spec["locals"]],
            source=spec.get("source") or {},
        )
    raise ValueError(f"Unknown seed specification {spec['kind']!r}.")


def _statement(seed) -> dict[str, Any]:
    spec = render_replay(seed)
    return {
        "expression": spec.expression,
        "local_names": list(spec.local_names),
        "universe_levels": list(spec.universe_levels),
        "fingerprint": spec.fingerprint,
    }


def generated_source(statement: dict[str, Any], imports: list[str]) -> str:
    """The Lean file a goal-mode task stands for: its statement, binders introduced."""
    levels = statement["universe_levels"]
    universes = f".{{{', '.join(levels)}}}" if levels else ""
    lines = [
        "-- Generated by Mathematics-ai-atp from a goal-mode formal request.",
        *(f"import {name}" for name in imports),
        "",
        f"theorem {GENERATED_THEOREM}{universes} :",
        f"    {statement['expression']} := by",
    ]
    if statement["local_names"]:
        lines.append(f"  intro {' '.join(statement['local_names'])}")
    lines += ["  sorry", ""]
    return "\n".join(lines)


def admit_goal(
    request_input: GoalInput,
    *,
    store: ArtifactStore,
    imports: list[str],
    environment: dict[str, str],
    supports_universes: bool = True,
) -> AdmittedTask:
    try:
        seed = seed_from_text(
            goal=request_input.goal_text,
            hypotheses=list(request_input.hypotheses),
            source={"origin": "formal-goal"},
        )
        statement = _statement(seed)
    except ReplayInputError as exc:
        raise AdmissionRejected(f"input:{exc.reason.value}", str(exc)) from exc
    except ValueError as exc:
        raise AdmissionRejected("input:malformed-text", str(exc)) from exc
    declared, used = list(request_input.universe_levels), statement["universe_levels"]
    if len(set(declared)) != len(declared):
        raise AdmissionRejected("input:universe-levels", "universe_levels lists a level twice.")
    if set(declared) != set(used):
        raise AdmissionRejected(
            "input:universe-levels",
            f"The goal and context use universe levels {sorted(used)}, "
            f"but the request declares {sorted(declared)}.",
        )
    if declared and not supports_universes:
        raise AdmissionRejected(
            "input:unsupported-context", "This backend does not admit universe-polymorphic goals."
        )
    statement = {**statement, "universe_levels": declared}
    source_text = generated_source(statement, imports)
    try:
        source_ref = store.put(source_text.encode("utf-8"))
        seed_spec = {
            "kind": "text",
            "goal": request_input.goal_text,
            "hypotheses": list(request_input.hypotheses),
            "source": {"origin": "formal-goal"},
        }
        manifest = {
            "format": INPUT_MANIFEST_FORMAT,
            "kind": "goal",
            "input": request_input.model_dump(mode="json"),
            "seed": seed_spec,
            "statement": statement,
            "source_artifact_hash": source_ref,
            "source_origin": "generated-from-text",
            **environment,
        }
        input_ref = store.put_json(manifest)
    except ArtifactError as exc:
        raise AdmissionRejected(exc.category, exc.detail) from exc
    return AdmittedTask(
        "goal", seed_spec, statement, manifest, input_ref, source_ref,
        "generated-from-text", request_input.goal_text,
    )


# Source inputs ------------------------------------------------------------------

_IMPORT = re.compile(r"^import\s+([^\s]+)\s*$")
_DECL_HEAD = re.compile(
    r"^\s*(?:@\[[^\]]*\]\s*)*(?:(?:private|protected|noncomputable|nonrec|unsafe|partial)\s+)*"
    r"(theorem|lemma)\s+(«[^»]+»|[^\s:({\[⦃]+)"
)
_NAMESPACE = re.compile(r"^\s*namespace\s+([^\s]+)\s*$")
_END = re.compile(r"^\s*end(?:\s+([^\s]+))?\s*$")
_SECTION = re.compile(r"^\s*(?:noncomputable\s+)?section(?:\s+([^\s]+))?\s*$")


def split_header(text: str) -> tuple[list[str], str]:
    """The file's ``import`` lines and the body after them (as one string)."""
    lines = text.split("\n")
    imports: list[str] = []
    index = 0
    in_block_comment = False
    while index < len(lines):
        line = lines[index].strip()
        if in_block_comment:
            if "-/" in line:
                in_block_comment = False
            index += 1
            continue
        if not line or line.startswith("--"):
            index += 1
            continue
        if line.startswith("/-"):
            in_block_comment = "-/" not in line[2:]
            index += 1
            continue
        match = _IMPORT.match(line)
        if match is None:
            break
        imports.append(match.group(1))
        index += 1
    body = "\n".join(lines[index:])
    if any(_IMPORT.match(line.strip()) for line in lines[index:]):
        raise AdmissionRejected("input:malformed-source", "An import appears after the file header.")
    return imports, body


def _unquote(name: str) -> str:
    return name[1:-1] if name.startswith("«") and name.endswith("»") else name


def target_unit_signature(units: list[tuple[int, int]], body: bytes, declaration: str) -> tuple[int, int]:
    """The byte span of the target unit and the offset of its top-level ``:=``.

    ``units`` are the compilation-unit byte boundaries Lean reported for the
    body. Namespaces are tracked so ``declaration`` is matched as a full name.
    Only ``theorem``/``lemma`` declarations with a ``:=`` body are supported.
    """
    scopes: list[tuple[str, str]] = []  # ("namespace" | "section", name)
    found: list[tuple[int, int, int]] = []
    for start, end in units:
        text = body[start:end].decode("utf-8", errors="strict")
        if (match := _NAMESPACE.match(text)) is not None:
            scopes.append(("namespace", match.group(1)))
            continue
        if (match := _SECTION.match(text)) is not None:
            scopes.append(("section", match.group(1) or ""))
            continue
        if (match := _END.match(text)) is not None:
            if scopes:
                scopes.pop()
            continue
        head = _DECL_HEAD.match(text)
        if head is None:
            continue
        local = _unquote(head.group(2))
        prefix = ".".join(name for kind, name in scopes if kind == "namespace")
        full = local[1:] if local.startswith("_root_.") else (f"{prefix}.{local}" if prefix else local)
        if full.startswith("_root_."):
            full = full[len("_root_."):]
        if full != declaration:
            continue
        try:
            tokens = tokenize(text)
        except LexError as exc:
            raise AdmissionRejected("input:malformed-source", str(exc)) from exc
        depth = 0
        assign = None
        name_end = head.end()
        for token in tokens:
            if token.start < name_end:
                continue
            if token.text in ("(", "[", "{", "⦃", "⟨"):
                depth += 1
            elif token.text in (")", "]", "}", "⦄", "⟩"):
                depth -= 1
            elif depth == 0 and token.text == ":=":
                assign = token.start
                break
            elif depth == 0 and token.text in ("|", "where"):
                break
        if assign is None:
            raise AdmissionRejected(
                "input:unsupported-declaration",
                f"{declaration} has no top-level ':=' body (equations and 'where' are not supported).",
            )
        found.append((start, end, start + len(text[:assign].encode("utf-8"))))
    if not found:
        raise AdmissionRejected("input:declaration-not-found", f"No theorem {declaration} in the source.")
    if len(found) > 1:
        raise AdmissionRejected("input:declaration-ambiguous", f"{declaration} is declared more than once.")
    start, _end, assign = found[0]
    return start, assign


SourceElaborator = Callable[[dict[str, Any]], Awaitable[dict[str, Any]]]


def _allowed_import(module: str, environment_imports: list[str]) -> bool:
    if module in ("Init", "Std", "Lean") or module.startswith(("Init.", "Std.", "Lean.")):
        return True
    return any(module == root or module.startswith(root + ".") for root in environment_imports)


def source_seed(goal: dict[str, Any], declaration: str):
    """The structured seed and closed statement of an elaborated declaration goal."""
    try:
        seed = seed_from_records(
            goal["target_sexp"],
            [StructuredLocal(**record) for record in goal["locals"]],
            source={"origin": "formal-source", "theorem": declaration},
        )
        return seed, _statement(seed)
    except ReplayInputError as exc:
        raise AdmissionRejected(f"input:{exc.reason.value}", str(exc)) from exc


async def admit_source(
    request_input: SourceInput,
    *,
    store: ArtifactStore,
    imports: list[str],
    environment: dict[str, str],
    elaborate: SourceElaborator,
) -> AdmittedTask:
    """Admit a source-backed input through the backend's ``elaborate`` operation.

    ``elaborate({"body", "declaration"})`` runs the backend's Lean runtime
    (``source_elaboration``) and returns the goal at the declaration's
    ``sorry`` with a ``check`` of its closed statement in the deployment
    environment, or raises ``AdmissionRejected``.
    """
    try:
        data = store.get(request_input.artifact_hash)
    except ArtifactError as exc:
        raise AdmissionRejected(f"input:{exc.category}", exc.detail) from exc
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise AdmissionRejected("input:malformed-source", "The source artifact is not UTF-8.") from exc
    source_imports, body = split_header(text)
    unsupported = [name for name in source_imports if not _allowed_import(name, imports)]
    if unsupported:
        raise AdmissionRejected(
            "environment:unsupported-import",
            f"The deployment environment does not provide {unsupported}.",
        )
    goal = await elaborate({"body": body, "declaration": request_input.declaration})
    _seed, statement = source_seed(goal, request_input.declaration)
    check = goal.get("check") or {}
    if not check.get("ok"):
        raise AdmissionRejected(
            "input:unsupported-context",
            "The declaration's statement does not elaborate in the deployment environment "
            f"(it may depend on declarations of the source file): {check.get('error')}",
        )
    seed_spec = {
        "kind": "structured",
        "target_sexp": goal["target_sexp"],
        "locals": goal["locals"],
        "source": {"origin": "formal-source", "theorem": request_input.declaration},
    }
    manifest = {
        "format": INPUT_MANIFEST_FORMAT,
        "kind": "source",
        "input": request_input.model_dump(mode="json"),
        "source_imports": source_imports,
        "target_unit_start": goal.get("target_unit_start"),
        "seed": seed_spec,
        "statement": statement,
        "source_artifact_hash": request_input.artifact_hash,
        "source_origin": "caller-artifact",
        **environment,
    }
    try:
        input_ref = store.put_json(manifest)
    except ArtifactError as exc:
        raise AdmissionRejected(exc.category, exc.detail) from exc
    return AdmittedTask(
        "source", seed_spec, statement, manifest, input_ref, request_input.artifact_hash,
        "caller-artifact", goal.get("target_pp") or request_input.declaration,
    )


def manifest_task(manifest: dict[str, Any], input_ref: str) -> AdmittedTask:
    """Rebuild an admitted task from its stored manifest (retry, restart, replay)."""
    return AdmittedTask(
        manifest["kind"],
        manifest["seed"],
        manifest["statement"],
        manifest,
        input_ref,
        manifest["source_artifact_hash"],
        manifest["source_origin"],
        manifest["input"].get("goal_text") or manifest["input"].get("declaration") or "",
    )


def environment_fields(environment_id: str, environment_hash: str) -> dict[str, str]:
    return {"environment_id": environment_id, "environment_hash": environment_hash}
